#!/usr/bin/env python3
"""Generate docs/baseline-profile.md from the SPOTAPOD source JSON.

Stdlib only. This script is the single generator for the baseline profile.
The profile is a derived artifact and must never be hand edited. The drift
gate (tools/derive_gate.py) fails CI if the committed profile diverges from
the hash recorded at generation time.

Usage:
    python3 analysis/profile_dataset.py /path/to/podawaa2024_fixed.json

Regression note: this profiler counts records missing the linkedinPostId
key separately from records where the key is present. An earlier draft
crashed with KeyError because 3,364 records lack the field entirely. The
missing-key bug is now a named condition, not a crash.
"""
import collections
import datetime
import hashlib
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "docs" / "baseline-profile.md"
DERIVED_MANIFEST = REPO_ROOT / "checksums" / "derived.json"


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def decode_post_time(post_id):
    """LinkedIn activity IDs encode a millisecond timestamp in the top 41 bits."""
    return datetime.datetime.fromtimestamp((post_id >> 22) / 1000, datetime.timezone.utc)


def pct_val(sorted_list, q):
    return sorted_list[min(int(q * len(sorted_list)), len(sorted_list) - 1)]


def main(source_path):
    source_sha = sha256_file(source_path)
    with open(source_path, encoding="utf-8") as f:
        data = json.load(f)
    posts = data["Posts"]
    n = len(posts)

    missing_id = sum(1 for p in posts if "linkedinPostId" not in p)
    null_author = sum(1 for p in posts if not p.get("AuthorPublicIdentifier"))
    placeholder = {"This post has no content", "postNoContent",
                   "Cette publication n'a pas de contenu", ""}
    placeholder_content = sum(
        1 for p in posts if p.get("Content", "").strip() in placeholder)
    zero_views = sum(1 for p in posts if p.get("Views", 0) == 0)
    zero_likes = sum(1 for p in posts if p.get("Likes", 0) == 0)

    likes = sorted(p.get("Likes", 0) for p in posts)
    lv = [(p["Likes"], p["Views"]) for p in posts if p.get("Views", 0) > 0]
    ratios = sorted(l / v for l, v in lv)
    likes_exceed_views = sum(1 for l, v in lv if l > v)
    ratio_over_half = sum(1 for r in ratios if r > 0.5)

    authors = collections.Counter(
        p.get("AuthorPublicIdentifier") for p in posts
        if p.get("AuthorPublicIdentifier"))
    counts = sorted(authors.values(), reverse=True)

    ids = collections.Counter(
        p["linkedinPostId"] for p in posts if "linkedinPostId" in p)
    dup_id_rows = sum(c - 1 for c in ids.values() if c > 1)

    contents = collections.Counter(p.get("Content", "").strip() for p in posts)
    dup_content = sum(
        c for t, c in contents.items()
        if c > 1 and t and t not in placeholder)

    lens = sorted(len(p.get("Content", "")) for p in posts)
    sample = posts[:50000]
    nonascii = sum(
        1 for p in sample if re.search(r"[^\x00-\x7F]", p.get("Content", "")))

    dates = sorted(
        decode_post_time(p["linkedinPostId"]) for p in posts
        if p.get("linkedinPostId", 0) > 0)
    years = collections.Counter(dt.year for dt in dates)

    lines = []
    w = lines.append
    w("# Baseline Profile")
    w("")
    w("Generated by analysis/profile_dataset.py. Do not hand edit. "
      "The drift gate fails CI on manual changes to this file.")
    w("")
    w(f"Source file SHA256: `{source_sha}`")
    w("")
    w("## Record counts (VERIFIED, computed from the file)")
    w("")
    w(f"| Measure | Value |")
    w(f"|---|---|")
    w(f"| Total records | {n:,} |")
    w(f"| Unique author identifiers | {len(authors):,} |")
    w(f"| Records with null or missing author | {null_author:,} ({null_author/n:.1%}) |")
    w(f"| Records missing linkedinPostId | {missing_id:,} |")
    w(f"| Duplicate linkedinPostId rows | {dup_id_rows:,} |")
    w(f"| Records with placeholder or empty content | {placeholder_content:,} |")
    w(f"| Records sharing identical non-empty content | {dup_content:,} |")
    w("")
    w("## Engagement fields (VERIFIED)")
    w("")
    w(f"| Measure | Value |")
    w(f"|---|---|")
    w(f"| Records with zero Views | {zero_views:,} ({zero_views/n:.1%}) |")
    w(f"| Records with zero Likes | {zero_likes:,} |")
    w(f"| Likes p50 / p90 / p99 / max | {pct_val(likes,.5):,} / {pct_val(likes,.9):,} / {pct_val(likes,.99):,} / {max(likes):,} |")
    w(f"| Records with Views > 0 | {len(lv):,} |")
    w(f"| Like-to-view ratio p50 / p90 / p99 | {pct_val(ratios,.5):.4f} / {pct_val(ratios,.9):.4f} / {pct_val(ratios,.99):.4f} |")
    w(f"| Records with ratio above 0.5 | {ratio_over_half:,} |")
    w(f"| Records where Likes exceed Views | {likes_exceed_views:,} |")
    w("")
    w("Records where Likes exceed Views are flagged as measurement anomalies "
      "(INFERENCE: most plausibly a Views capture artifact, not necessarily "
      "evidence of manipulation on those specific posts).")
    w("")
    w("## Author concentration (VERIFIED)")
    w("")
    w(f"| Measure | Value |")
    w(f"|---|---|")
    w(f"| Top 10 authors, share of all records | {sum(counts[:10])/n:.1%} |")
    w(f"| Top 100 authors, share of all records | {sum(counts[:100])/n:.1%} |")
    w(f"| Authors with exactly 1 record | {sum(1 for c in counts if c == 1):,} |")
    w(f"| Authors with 100 or more records | {sum(1 for c in counts if c >= 100):,} |")
    w(f"| Largest single-author record count | {counts[0]:,} |")
    w("")
    w("## Content characteristics (VERIFIED)")
    w("")
    w(f"| Measure | Value |")
    w(f"|---|---|")
    w(f"| Content length p50 / p90 / max (chars) | {pct_val(lens,.5):,} / {pct_val(lens,.9):,} / {lens[-1]:,} |")
    w(f"| Records with non-ASCII content (first 50k sample) | {nonascii/len(sample):.1%} |")
    w("")
    w("## Temporal coverage (INFERENCE, decoded from post IDs)")
    w("")
    w("LinkedIn activity IDs encode a millisecond timestamp in the upper 41 "
      "bits. Decoding is a documented community technique, not a platform "
      "guarantee, so these dates carry the INFERENCE tier.")
    w("")
    w(f"| Measure | Value |")
    w(f"|---|---|")
    w(f"| Earliest decoded post date | {dates[0].date()} |")
    w(f"| Latest decoded post date | {dates[-1].date()} |")
    for y in sorted(years):
        w(f"| Posts decoded to {y} | {years[y]:,} |")
    w("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")

    profile_sha = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()
    manifest = {
        "source_file": Path(source_path).name,
        "source_sha256": source_sha,
        "derived": {"docs/baseline-profile.md": profile_sha},
    }
    DERIVED_MANIFEST.write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT} ({profile_sha[:12]}...) and {DERIVED_MANIFEST}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: profile_dataset.py /path/to/podawaa2024_fixed.json")
    main(sys.argv[1])
